/** One season of ideas, by the number it goes by. */
export function themeOf(seasonNo) {
  return THEME_SEASONS.find((season) => season.no === seasonNo) || null;
}

/**
 * The idea one episode is met under. Every episode of a season carries its own, so no two episodes of a
 * season stand under the same idea; a season that is not one of these, or an episode outside its run,
 * carries none.
 */
export function episodeIdea(seasonNo, episode) {
  const season = themeOf(Number(seasonNo));
  const no = Number(episode);
  if (!season || !Number.isInteger(no) || no < 1) return "";
  return season.ideas[no - 1] || "";
}