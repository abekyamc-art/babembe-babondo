/** Every word of the studio, in the language asked for. */
export function textFor(lang) {
  return lang === "en" ? EN : SW;
}

const STORE_KEY = "gloire-studio-lang";

/** The language the studio last answered in. Kiswahili leads, as the rest of the app does. */
export function readStudioLang() {
  try {
    const saved = localStorage.getItem(STORE_KEY);
    return saved === "en" || saved === "sw" ? saved : "sw";
  } catch (err) {
    return "sw";
  }
}

export function writeStudioLang(lang) {
  try {
    localStorage.setItem(STORE_KEY, lang);
  } catch (err) {
    // a browser that keeps nothing still switches for this visit
  }
}